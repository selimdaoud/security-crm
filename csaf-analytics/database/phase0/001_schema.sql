create or replace view csaf_latest_enrichment_v as
select cve,
       observed_date,
       epss,
       epss_percentile,
       kev,
       kev_added,
       kev_due,
       kev_ransomware,
       public_exploits,
       exploit_url,
       epss_status,
       kev_status,
       exploit_status,
       imported_at,
       last_batch_id
  from (
    select e.*,
           row_number() over (
             partition by e.cve
             order by e.observed_date desc, e.imported_at desc
           ) as rn
      from csaf_enrichment e
  )
 where rn = 1;

